export function getAsrFacilitiesSummary() {
  const total = ASR_DISTRICT_FACILITIES.length
  const totalBeds = ASR_DISTRICT_FACILITIES.reduce((acc, f) => acc + f.totalBeds, 0)
  const activeBeds = ASR_DISTRICT_FACILITIES.reduce((acc, f) => acc + f.activeBeds, 0)
  const totalAmbulances = ASR_DISTRICT_FACILITIES.reduce((acc, f) => acc + f.ambulancesAvailable, 0)
  const totalCaseload = ASR_DISTRICT_FACILITIES.reduce((acc, f) => acc + f.activeCaseload, 0)
  const phcsCount = ASR_DISTRICT_FACILITIES.filter((f) => f.type === 'PHC').length
  const hospitalsCount = ASR_DISTRICT_FACILITIES.filter((f) => f.type !== 'PHC').length

  return {
    totalFacilities: total,
    phcsCount,
    hospitalsCount,
    totalBeds,
    activeBeds,
    vacantBeds: totalBeds - activeBeds,
    occupancyRate: ((activeBeds / totalBeds) * 100).toFixed(1),
    totalAmbulances,
    totalCaseload,
    verifiedDoctorsCount: total,
  }
}

