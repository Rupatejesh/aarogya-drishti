// Global WeakMaps to store pristine original English content
const textNodeOriginals = new WeakMap<Node, string>();
const textNodeLastRendered = new WeakMap<Node, string>();
const elementPlaceholderOriginals = new WeakMap<Element, string>();
const elementPlaceholderLastRendered = new WeakMap<Element, string>();
const elementTitleOriginals = new WeakMap<Element, string>();
const elementTitleLastRendered = new WeakMap<Element, string>();

// Sorted dictionary keys by length descending to match full phrases before individual words
const sortedKeys = Object.keys(dictionary).sort((a, b) => b.length - a.length);
const sortedWordKeys = Object.keys(wordDictionary).sort((a, b) => b.length - a.length);

export function translateValue(original: string, lang: Language): string {
  if (lang === 'en' || !original) return original;

  const trimmed = original.trim();
  if (dictionary[trimmed]?.[lang]) return original.replace(trimmed, dictionary[trimmed][lang]);
  if (wordDictionary[trimmed]?.[lang]) return original.replace(trimmed, wordDictionary[trimmed][lang]);

  let translated = original;
  for (const phrase of sortedKeys) {
    const replacement = dictionary[phrase]?.[lang];
    if (phrase.length > 2 && replacement && translated.includes(phrase)) translated = translated.split(phrase).join(replacement);
  }
  for (const word of sortedWordKeys) {
    const regex = new RegExp(`\\b${word}\\b`, 'gi');
    if (regex.test(translated)) translated = translated.replace(regex, wordDictionary[word][lang]);
  }
  return translated;
}

// Concurrency flag to prevent recursive MutationObserver loops
let isTranslating = false;

/**
 * Traverses DOM nodes and dynamically translates visible text, placeholders, and titles.
 * Guarantees 100% translation coverage across every section of the application.
 */
export function applyDOMTranslation(root: HTMLElement, lang: Language) {
  if (!root || isTranslating) return;

  try {
    isTranslating = true;

    // 1. Walk Text Nodes
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: (node) => {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (['script', 'style', 'code', 'pre', 'noscript'].includes(tag)) {
          return NodeFilter.FILTER_REJECT;
        }
        if (parent.closest('.notranslate, [translate="no"]')) {
          return NodeFilter.FILTER_REJECT;
        }
        if (!node.nodeValue || node.nodeValue.trim().length === 0) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });

    const nodesToUpdate: { node: Node; newText: string }[] = [];

    let currentNode = walker.nextNode();
    while (currentNode) {
      let original = textNodeOriginals.get(currentNode);
      const currentText = currentNode.nodeValue || '';
      const lastRendered = textNodeLastRendered.get(currentNode);
      if (original === undefined) {
        original = currentText;
        textNodeOriginals.set(currentNode, original);
      } else if (currentText !== lastRendered && currentText !== original && translateValue(original, lang) !== currentText) {
        // React may reuse a text node for a new label or status. Keep its new source text.
        original = currentText;
        textNodeOriginals.set(currentNode, original);
      }

      if (lang === 'en') {
        if (currentNode.nodeValue !== original) {
          nodesToUpdate.push({ node: currentNode, newText: original });
        }
        textNodeLastRendered.set(currentNode, original);
      } else {
        const translated = translateValue(original, lang);

        if (translated !== currentNode.nodeValue) {
          nodesToUpdate.push({ node: currentNode, newText: translated });
        }
        textNodeLastRendered.set(currentNode, translated);
      }

      currentNode = walker.nextNode();
    }

    // Apply batch updates
    for (const { node, newText } of nodesToUpdate) {
      node.nodeValue = newText;
    }

    // 2. Input/Textarea Placeholders Translation
    const inputs = root.querySelectorAll('input[placeholder], textarea[placeholder]');
    inputs.forEach((el) => {
      const inputEl = el as HTMLInputElement | HTMLTextAreaElement;
      let original = elementPlaceholderOriginals.get(inputEl);
      const currentPlaceholder = inputEl.placeholder;
      const lastRendered = elementPlaceholderLastRendered.get(inputEl);
      if (original === undefined) {
        original = currentPlaceholder;
        elementPlaceholderOriginals.set(inputEl, original);
      } else if (currentPlaceholder !== lastRendered && currentPlaceholder !== original && translateValue(original, lang) !== currentPlaceholder) {
        original = currentPlaceholder;
        elementPlaceholderOriginals.set(inputEl, original);
      }

      if (lang === 'en') {
        inputEl.placeholder = original;
      } else {
        inputEl.placeholder = translateValue(original, lang);
      }
      elementPlaceholderLastRendered.set(inputEl, inputEl.placeholder);
    });

    // 3. Titles / Tooltips Translation
    const titled = root.querySelectorAll('[title]');
    titled.forEach((el) => {
      const elHtml = el as HTMLElement;
      let original = elementTitleOriginals.get(el);
      const currentTitle = elHtml.getAttribute('title') || '';
      const lastRendered = elementTitleLastRendered.get(el);
      if (original === undefined) {
        original = currentTitle;
        elementTitleOriginals.set(el, original);
      } else if (currentTitle !== lastRendered && currentTitle !== original && translateValue(original, lang) !== currentTitle) {
        original = currentTitle;
        elementTitleOriginals.set(el, original);
      }

      if (lang === 'en') {
        elHtml.setAttribute('title', original);
      } else {
        elHtml.setAttribute('title', translateValue(original, lang));
      }
      elementTitleLastRendered.set(elHtml, elHtml.getAttribute('title') || '');
    });
  } finally {
    isTranslating = false;
  }
}
